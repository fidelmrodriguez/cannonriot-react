function readStoredLanguage(): Language {
  try {
    const value = localStorage.getItem(STORAGE_KEY);
    return value === 'pt' || value === 'es' || value === 'en' ? value : 'en';
  } catch {
    return 'en';
  }
}

currentLanguage = typeof window === 'undefined' ? 'en' : readStoredLanguage();
if (typeof document !== 'undefined') document.documentElement.lang = currentLanguage === 'pt' ? 'pt-BR' : currentLanguage;

export function getLanguage(): Language {
  return currentLanguage;
}

export function setLanguage(language: Language): void {
  currentLanguage = language;
  if (typeof document !== 'undefined') document.documentElement.lang = language === 'pt' ? 'pt-BR' : language;
  try { localStorage.setItem(STORAGE_KEY, language); } catch { /* storage may be unavailable */ }
}

export function getLocale(language: Language = currentLanguage): string {
  if (language === 'pt') return 'pt-BR';
  if (language === 'es') return 'es-ES';
  return 'en-US';
}

export function t(key: string, vars: Record<string, string | number> = {}, language: Language = currentLanguage): string {
  let value = dictionaries[language][key] ?? dictionaries.en[key] ?? key;
  for (const [name, replacement] of Object.entries(vars)) value = value.replaceAll(`{${name}}`, String(replacement));
  return value;
}

